// Generates the MD3 color tokens (light + dark) from the seed in design/tokens/seed.json.
// Output: src/styles/md3-tokens.generated.css, consumed by src/styles/main.css.
// Runs before dev/build/test (see package.json pre-scripts). The shared token rules are in design/tokens/README.md.
//
// The color library ships extensionless ESM imports that Node cannot resolve natively,
// so it is loaded through Vite's module loader.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createServer } from 'vite'

// import.meta.dirname (not a file URL) so the module also resolves inside Vitest, which imports it in the parity test.
const HERE = import.meta.dirname
const SOURCE = join(HERE, '../../design/tokens/seed.json')
const OUT = join(HERE, '../src/styles/md3-tokens.generated.css')
const { seed: SEED } = JSON.parse(readFileSync(SOURCE, 'utf8'))

// MD3 color role (kebab-case CSS name) -> MaterialDynamicColors property.
const ROLES = {
  'primary': 'primary',
  'on-primary': 'onPrimary',
  'primary-container': 'primaryContainer',
  'on-primary-container': 'onPrimaryContainer',
  'inverse-primary': 'inversePrimary',
  'secondary': 'secondary',
  'on-secondary': 'onSecondary',
  'secondary-container': 'secondaryContainer',
  'on-secondary-container': 'onSecondaryContainer',
  'tertiary': 'tertiary',
  'on-tertiary': 'onTertiary',
  'tertiary-container': 'tertiaryContainer',
  'on-tertiary-container': 'onTertiaryContainer',
  'error': 'error',
  'on-error': 'onError',
  'error-container': 'errorContainer',
  'on-error-container': 'onErrorContainer',
  'surface-dim': 'surfaceDim',
  'surface': 'surface',
  'surface-bright': 'surfaceBright',
  'surface-container-lowest': 'surfaceContainerLowest',
  'surface-container-low': 'surfaceContainerLow',
  'surface-container': 'surfaceContainer',
  'surface-container-high': 'surfaceContainerHigh',
  'surface-container-highest': 'surfaceContainerHighest',
  'on-surface': 'onSurface',
  'on-surface-variant': 'onSurfaceVariant',
  'surface-variant': 'surfaceVariant',
  'outline': 'outline',
  'outline-variant': 'outlineVariant',
  'inverse-surface': 'inverseSurface',
  'inverse-on-surface': 'inverseOnSurface',
  'surface-tint': 'surfaceTint',
  'background': 'background',
  'on-background': 'onBackground',
  'shadow': 'shadow',
  'scrim': 'scrim',
}

/** The generated stylesheet as a string, for the write below and for the parity test. */
export async function renderMd3Css() {
  const { hexFromArgb, argbFromHex, Hct, SchemeTonalSpot, MaterialDynamicColors } = await loadLibrary()

  const seed = Hct.fromInt(argbFromHex(SEED))
  const scheme = (isDark) => {
    const s = new SchemeTonalSpot(seed, isDark, 0)
    return Object.fromEntries(
      Object.entries(ROLES).map(([css, prop]) => [css, hexFromArgb(MaterialDynamicColors[prop].getArgb(s))]),
    )
  }

  const light = scheme(false)
  const dark = scheme(true)

  const decl = (values) =>
    Object.entries(values)
      .map(([css, hex]) => `  --md-sys-color-${css}: ${hex};`)
      .join('\n')

  return `/* Generated by scripts/generate-md3-tokens.mjs from seed ${SEED}. Do not edit. */

/* Light scheme is the default. */
:root {
  color-scheme: light;
${decl(light)}
}

/* Dark scheme follows the OS preference unless the user chose light explicitly... */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${decl(dark)}
  }
}

/* ...or the user chose dark explicitly. */
:root[data-theme="dark"] {
  color-scheme: dark;
${decl(dark)}
}
`
}

// Run as a script (npm run generate:tokens); importing the module, e.g. from the parity test, writes nothing.
if (process.argv[1] === join(HERE, 'generate-md3-tokens.mjs')) {
  writeFileSync(OUT, await renderMd3Css())
  console.log(`MD3 tokens written to ${OUT}`)
}

async function loadLibrary() {
  const server = await createServer({
    configFile: false,
    server: { middlewareMode: true },
    appType: 'custom',
    logLevel: 'silent',
  })
  try {
    const m = await server.ssrLoadModule('@material/material-color-utilities')
    return m
  } finally {
    await server.close()
  }
}
