-- Integration detections (integration-evidence capability, part 2 of 3): one row per detection a registered
-- integration submitted. Personal data: owner is the SHA-512 hash of the Minecraft UUID (never the raw UUID), and
-- the row follows the retention of IntegrationDetectionSweeper until it is attached as evidence.
-- (integration_id, detection_id) is the idempotency key: a repeated detection is a no-op.
-- attached_evidence_id is set by the attach path of the next migration's change; no foreign key yet.
CREATE TABLE integration_detection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    integration_id bigint NOT NULL REFERENCES integration (id),
    detection_id uuid NOT NULL,
    kind varchar(32) NOT NULL,
    schema_version smallint NOT NULL,
    owner char(128) NOT NULL,
    server varchar(64) NOT NULL,
    occurred_at bigint NOT NULL,
    received_at bigint NOT NULL,
    severity varchar(16),
    summary varchar(200) NOT NULL,
    payload jsonb NOT NULL,
    attached_evidence_id uuid,
    CONSTRAINT integration_detection_key UNIQUE (integration_id, detection_id),
    CONSTRAINT integration_detection_severity_check CHECK (severity IS NULL OR severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE INDEX integration_detection_owner_occurred_idx ON integration_detection (owner, occurred_at);
CREATE INDEX integration_detection_received_idx ON integration_detection (received_at);
