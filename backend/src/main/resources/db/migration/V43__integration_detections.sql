-- Integration registry (integration-evidence capability, part 1 of 3): one row per third-party detection source
-- (for example Vulcan) and the Entra client ids allowed to report for it. A registration is written only by an
-- administrator and every write is audited. The client secret is never stored: it lives in Entra.
-- allowed_tasks (CloudNet task names, for dynamic services) and allowed_static_servers (exact server names) bound
-- the server labels a client may report for; a registration needs at least one of them.
-- created_by_oid and updated_by_oid are the verified administrators (no foreign key, like the other recorded_by_oid).
-- Detections and their table follow in V44 and V45; nothing in this file is read by the evidence path.
CREATE TABLE integration (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system varchar(64) NOT NULL,
    entra_client_id varchar(64) NOT NULL,
    display_name varchar(128) NOT NULL,
    enabled boolean NOT NULL,
    allowed_kinds text[] NOT NULL,
    allowed_tasks text[] NOT NULL,
    allowed_static_servers text[] NOT NULL,
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    created_by_oid uuid NOT NULL,
    updated_by_oid uuid NOT NULL,
    CONSTRAINT integration_source_system_key UNIQUE (source_system),
    CONSTRAINT integration_entra_client_id_key UNIQUE (entra_client_id),
    CONSTRAINT integration_scope_check CHECK (cardinality(allowed_tasks) + cardinality(allowed_static_servers) > 0),
    CONSTRAINT integration_kinds_check CHECK (cardinality(allowed_kinds) > 0)
);
