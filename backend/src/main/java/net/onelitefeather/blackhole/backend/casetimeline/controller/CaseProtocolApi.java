package net.onelitefeather.blackhole.backend.casetimeline.controller;

import io.micronaut.core.annotation.Nullable;
import io.micronaut.http.HttpResponse;
import io.micronaut.http.annotation.Get;
import io.micronaut.http.annotation.PathVariable;
import io.micronaut.http.annotation.QueryValue;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import net.onelitefeather.blackhole.backend.casetimeline.dto.CaseProtocolDTO;
import net.onelitefeather.blackhole.backend.security.Actor;

import java.util.UUID;

/**
 * The stored appeal protocols of a case: the conversation of every decided appeal, generated by the
 * backend from the case events and kept as evidence. Staff only; a protocol holds {@code STAFF}
 * visibility entries, so every open and download is audited.
 */
public interface CaseProtocolApi {

    @Operation(
            summary = "List the stored protocols of a case",
            description = "The readable versions of the protocols of every appeal of the case, newest first. A version that a "
                    + "redaction made unreadable is not listed.",
            operationId = "listCaseProtocols",
            tags = {"Case"}
    )
    @ApiResponse(responseCode = "200", description = "The readable versions",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.ListResponse.class)))
    @ApiResponse(responseCode = "404", description = "Unknown punishment",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.Error.class)))
    @ApiResponse(responseCode = "409", description = "The short id matches several punishments",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.Error.class)))
    @Get("/{reference}/protocol")
    HttpResponse<CaseProtocolDTO> listProtocols(@PathVariable String reference);

    @Operation(
            summary = "Open the text of a stored protocol",
            description = "The human-readable rendering of one version, addressed by its evidence id. Writes a VIEWED audit entry. "
                    + "The response is never cached.",
            operationId = "openCaseProtocol",
            tags = {"Case"}
    )
    @ApiResponse(responseCode = "200", description = "The text",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.TextResponse.class)))
    @ApiResponse(responseCode = "404", description = "Unknown punishment, unknown protocol, or a version a redaction made unreadable",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.Error.class)))
    @ApiResponse(responseCode = "503", description = "The file store is unavailable",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.Error.class)))
    @Get("/{reference}/protocol/{evidenceId}")
    HttpResponse<CaseProtocolDTO> openProtocol(@PathVariable String reference, @PathVariable UUID evidenceId, @Parameter(hidden = true) Actor actor);

    @Operation(
            summary = "Download a stored protocol",
            description = "The text or the JSON of one version as an attachment, with X-Content-Type-Options: nosniff, "
                    + "Content-Security-Policy: sandbox and Cache-Control: private, no-store. Writes a DOWNLOADED audit entry.",
            operationId = "downloadCaseProtocol",
            tags = {"Case"}
    )
    @ApiResponse(responseCode = "200", description = "The file (Content-Disposition: attachment)",
            content = {
                    @Content(mediaType = "text/plain", schema = @Schema(type = "string")),
                    @Content(mediaType = "application/json", schema = @Schema(type = "string"))
            })
    @ApiResponse(responseCode = "400", description = "Unknown format",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.Error.class)))
    @ApiResponse(responseCode = "404", description = "Unknown punishment, unknown protocol, or a version a redaction made unreadable",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = CaseProtocolDTO.Error.class)))
    @Get("/{reference}/protocol/{evidenceId}/download")
    HttpResponse<?> downloadProtocol(
            @PathVariable String reference, @PathVariable UUID evidenceId, @Nullable @QueryValue String format,
            @Parameter(hidden = true) Actor actor);
}
